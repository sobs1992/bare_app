#!/usr/bin/env python3
"""
gen_font.py: TTF/OTF -> LVGL 9 bitmap font (lv_font_fmt_txt, 4 bpp) as C source.

Stands in for lv_font_conv (Node.js + npm) with Python and Pillow only.
Covers ASCII, a few typographic signs and Cyrillic; the LV_SYMBOL_* icons
come from the fallback font (a built-in Montserrat of the same size).

  tools/gen_font.py --size 20 --name ui_font_20 --fallback lv_font_montserrat_20 \
      -o src/gui/view/lvgl/fonts/ui_font_20.c [--font /path/to/font.ttf]
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

DEFAULT_FONT = "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf"

CHARS = (list(range(0x20, 0x7F))                 # ASCII
         + [0xA0, 0xAB, 0xB0, 0xBB, 0xD7]        # nbsp « ° » ×
         + [0x401] + list(range(0x410, 0x450)) + [0x451]   # Ё А..я ё
         + [0x2013, 0x2014, 0x2026, 0x2116])     # – — … №


def render(font, cp, bpp):
    ch = chr(cp)
    adv = font.getlength(ch)
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")   # relative to the baseline
    w, h = max(x1 - x0, 0), max(y1 - y0, 0)
    pixels = []
    if w and h:
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        levels = (1 << bpp) - 1
        pixels = [(p * levels + 127) // 255 for p in img.tobytes()]
    else:
        w = h = 0
    return {
        "cp": cp, "adv_w": round(adv * 16), "box_w": w, "box_h": h,
        "ofs_x": x0, "ofs_y": -y1,              # bottom of the box, up is positive
        "pixels": pixels,
    }


def pack(pixels, bpp):
    """Rows packed back to back, most significant bits first (LVGL 'plain' format)."""
    out, acc, nbits = bytearray(), 0, 0
    for p in pixels:
        acc = (acc << bpp) | p
        nbits += bpp
        if nbits == 8:
            out.append(acc)
            acc, nbits = 0, 0
    if nbits:
        out.append(acc << (8 - nbits))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font", default=DEFAULT_FONT)
    ap.add_argument("--size", type=int, required=True, help="pixels per em")
    ap.add_argument("--name", required=True, help="C name of the lv_font_t")
    ap.add_argument("--fallback", help="lv_font_t used for missing glyphs (icons)")
    ap.add_argument("--bpp", type=int, default=4, choices=(1, 2, 4, 8))
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()

    font = ImageFont.truetype(a.font, a.size)
    ascent, descent = font.getmetrics()
    glyphs = [render(font, cp, a.bpp) for cp in CHARS]
    for g in glyphs:
        if not (0 <= g["adv_w"] < 4096 and -128 <= g["ofs_x"] < 128 and -128 <= g["ofs_y"] < 128):
            raise SystemExit("gen_font: glyph U+%04X does not fit the small format" % g["cp"])
    cap_h = -font.getbbox("H", anchor="ls")[1]
    x_h = -font.getbbox("x", anchor="ls")[1]

    bitmap, index = bytearray(), []
    for g in glyphs:
        index.append(len(bitmap))
        bitmap += pack(g["pixels"], a.bpp)

    start = CHARS[0]
    L = []
    L.append("/*")
    L.append(" * %s: %d px, %d bpp, generated by tools/gen_font.py from" % (a.name, a.size, a.bpp))
    L.append(" * %s" % os.path.basename(a.font))
    L.append(" * Noto Sans: Copyright 2022 The Noto Project Authors, SIL Open Font License 1.1.")
    L.append(" * Do not edit, regenerate instead.")
    L.append(" */")
    L.append('#include "lvgl.h"')
    L.append("")
    L.append("static const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        L.append("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 16]) + ",")
    L.append("};")
    L.append("")
    L.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    L.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}, /* id 0 reserved */")
    for g, idx in zip(glyphs, index):
        L.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, /* U+%04X */"
                 % (idx, g["adv_w"], g["box_w"], g["box_h"], g["ofs_x"], g["ofs_y"], g["cp"]))
    L.append("};")
    L.append("")
    L.append("static const uint16_t unicode_list[] = {")
    offs = [cp - start for cp in CHARS]
    for i in range(0, len(offs), 12):
        L.append("    " + ", ".join("0x%04x" % o for o in offs[i:i + 12]) + ",")
    L.append("};")
    L.append("")
    L.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    L.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = 1," % (start, CHARS[-1] - start + 1))
    L.append("     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = %d," % len(CHARS))
    L.append("     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY},")
    L.append("};")
    L.append("")
    L.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    L.append("    .glyph_bitmap = glyph_bitmap,")
    L.append("    .glyph_dsc = glyph_dsc,")
    L.append("    .cmaps = cmaps,")
    L.append("    .kern_dsc = NULL,")
    L.append("    .kern_scale = 0,")
    L.append("    .cmap_num = 1,")
    L.append("    .bpp = %d," % a.bpp)
    L.append("    .kern_classes = 0,")
    L.append("    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,")
    L.append("};")
    L.append("")
    if a.fallback:
        L.append("extern const lv_font_t %s;" % a.fallback)
        L.append("")
    L.append("const lv_font_t %s = {" % a.name)
    L.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    L.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    L.append("    .line_height = %d," % (ascent + descent))
    L.append("    .base_line = %d," % descent)
    L.append("    .cap_height = %d," % cap_h)
    L.append("    .x_height = %d," % x_h)
    L.append("    .subpx = LV_FONT_SUBPX_NONE,")
    L.append("    .underline_position = %d," % -max(1, a.size // 10))
    L.append("    .underline_thickness = %d," % max(1, a.size // 14))
    L.append("    .static_bitmap = 1,")
    L.append("    .dsc = &font_dsc,")
    L.append("    .fallback = %s," % ("&" + a.fallback if a.fallback else "NULL"))
    L.append("    .user_data = NULL,")
    L.append("};")
    with open(a.output, "w") as f:
        f.write("\n".join(L) + "\n")
    print("%s: %d glyphs, %d bytes of bitmaps, line %d px" % (a.output, len(glyphs), len(bitmap), ascent + descent))


if __name__ == "__main__":
    main()
