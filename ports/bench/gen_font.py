#!/usr/bin/env python3
"""
gen_font.py: the text of bare_app_bench as 8-bit coverage bitmaps in a C
header (font.h), from the UI's font (Noto Sans) with Pillow.

  ports/bench/gen_font.py -o ports/bench/font.h

Two faces: FONT_TEXT (regular, the lines) and FONT_BIG (bold, the verdict).
ASCII, a few signs and Cyrillic, as tools/gen_font.py.
"""
import argparse

from PIL import Image, ImageDraw, ImageFont

FACES = [
    ("text", "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf", 17),
    ("big", "/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf", 30),
]

CHARS = (list(range(0x20, 0x7F))                 # ASCII
         + [0xB0, 0xB1, 0xD7]                    # ° ± ×
         + [0x401] + list(range(0x410, 0x450)) + [0x451]   # Ё А..я ё
         + [0x2013, 0x2014, 0x2026, 0x2212])     # – — … −


def glyphs(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    out = []
    for cp in CHARS:
        ch = chr(cp)
        adv = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(x1 - x0, 0), max(y1 - y0, 0)
        pix = b""
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            pix = img.tobytes()
        out.append((cp, adv, w, h, x0, y0, pix))   # y0: top of the box from the baseline
    return ascent, descent, out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()
    lines = ["/* Generated by ports/bench/gen_font.py from Noto Sans (SIL OFL 1.1): do not edit */",
             "#pragma once", "#include <stdint.h>", "",
             "struct bench_glyph { uint16_t cp; uint8_t adv, w, h; int8_t x, y; uint32_t pix; };",
             "struct bench_font { int ascent, descent; const struct bench_glyph *g; int n;"
             " const uint8_t *pix; };", ""]
    for name, path, size in FACES:
        ascent, descent, gl = glyphs(path, size)
        blob = bytearray()
        rows = []
        for cp, adv, w, h, x, y, pix in gl:
            rows.append(f"\t{{ 0x{cp:04x}, {adv}, {w}, {h}, {x}, {y}, {len(blob)} }},")
            blob += pix
        lines.append(f"static const struct bench_glyph font_{name}_glyphs[] = {{")
        lines += rows
        lines.append("};")
        lines.append(f"static const uint8_t font_{name}_pix[{len(blob)}] = {{")
        for i in range(0, len(blob), 24):
            lines.append("\t" + ", ".join(str(b) for b in blob[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const struct bench_font font_{name} = {{ {ascent}, {descent}, "
                     f"font_{name}_glyphs, {len(gl)}, font_{name}_pix }};")
        lines.append("")
    with open(args.output, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
